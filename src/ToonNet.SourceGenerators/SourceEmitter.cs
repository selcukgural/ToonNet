using Microsoft.CodeAnalysis.CSharp;
using ToonNet.SourceGenerators.Model;
using ToonNet.SourceGenerators.Utilities;

namespace ToonNet.SourceGenerators;

/// <summary>
/// Writes the generated partial type: the public <c>Serialize</c>/<c>Deserialize</c> methods, the
/// <c>__ToonSerializeValue</c>/<c>__ToonDeserializeValue</c> methods other generated types call, and one helper
/// method per collection or dictionary type.
/// </summary>
/// <remarks>
/// Generated code runs only when the options contain no converters; otherwise (and for derived runtime types) it
/// defers to <c>ToonSerializer</c>, so the output is always the same as the reflection-based serializer's.
/// A module initializer registers the methods, so <c>ToonSerializer</c> calls them for values of the type.
/// </remarks>
internal sealed class SourceEmitter
{
    private const string Models = "global::ToonNet.Core.Models.";
    private const string Serialization = "global::ToonNet.Core.Serialization.";
    private const string Serializer = Serialization + "ToonSerializer";
    private const string Helpers = Serialization + "ToonSourceGenerationHelpers";
    private const string Options = Serialization + "ToonSerializerOptions";
    private const string Writer = "global::ToonNet.Core.Encoding.ToonWriter";
    private const string RowShape = Serialization + "ToonRowShape";
    private const string HiddenAttribute = "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]";

    private readonly TypeModel _model;
    private readonly CodeBuilder _code = new();
    private readonly Dictionary<string, int> _writerIds = new(StringComparer.Ordinal);
    private readonly Dictionary<string, int> _readerIds = new(StringComparer.Ordinal);
    private readonly List<(int Id, ValuePlan Plan)> _writers = [];
    private readonly List<(int Id, ValuePlan Plan)> _readers = [];
    private readonly Dictionary<string, int> _textReaderIds = new(StringComparer.Ordinal);
    private readonly List<(int Id, ValuePlan Plan)> _textReaders = [];
    private int _variable;

    /// <summary>Whether the code calls <c>__ToonIsMapped</c>, which is then emitted once.</summary>
    private bool _isMappedUsed;

    private SourceEmitter(TypeModel model) => _model = model;

    public static string Emit(TypeModel model) => new SourceEmitter(model).Run();

    private string Run()
    {
        var code = _code;

        code.AppendLine("// <auto-generated />");
        code.AppendLine("#nullable enable annotations");
        code.AppendLine("#nullable disable warnings");
        code.AppendLine("#pragma warning disable CS0612, CS0618 // Obsolete members are serialized like any other");
        code.AppendLine("#pragma warning disable CS0108, CS0109 // The static members of a generated base type are hidden on purpose (always called through the type)");
        code.AppendLine();

        if (_model.Namespace != null)
        {
            code.AppendLine($"namespace {_model.Namespace};");
            code.AppendLine();
        }

        foreach (var containing in _model.ContainingTypeDeclarations)
        {
            code.BeginBlock(containing);
        }

        if (_model.Documentation)
        {
            code.AppendLine("/// <summary>");
            code.AppendLine("/// Generated TOON serialization methods.");
            code.AppendLine("/// </summary>");
        }

        code.BeginBlock(_model.Declaration);

        EmitConverterFields();
        EmitRegistration();
        EmitSerialize();

        if (EmitsFieldWriter)
        {
            EmitFieldWriter();
        }

        if (_model.Constructor != null)
        {
            code.AppendLine();
            EmitDeserialize(_model.Constructor);

            if (EmitsTextReader)
            {
                EmitTextReader(_model.Constructor);
            }

            EmitAccessors();

            if (_isMappedUsed)
            {
                EmitIsMapped(_model.Constructor);
            }
        }

        EmitHelperMethods();

        code.EndBlock();

        foreach (var _ in _model.ContainingTypeDeclarations)
        {
            code.EndBlock();
        }

        return code.ToString();
    }

    private void EmitConverterFields()
    {
        var any = false;

        foreach (var property in _model.Properties)
        {
            if (property.ConverterTypeName == null)
            {
                continue;
            }

            _code.AppendLine($"private static readonly {Serialization}IToonConverter {ConverterField(property)} = new {property.ConverterTypeName}();");
            any = true;
        }

        if (any)
        {
            _code.AppendLine();
        }
    }

    /// <summary>
    /// A module initializer that registers the generated methods, so <c>ToonSerializer</c> uses them for this type.
    /// </summary>
    private void EmitRegistration()
    {
        if (!_model.RegisterWithSerializer)
        {
            return;
        }

        var deserialize = _model.Constructor != null ? "__ToonDeserializeValue" : "null";
        var writer = EmitsFieldWriter || EmitsTextReader
            ? $", {(EmitsFieldWriter ? "new __ToonObjectWriter()" : "null")}, {(EmitsTextReader ? "new __ToonObjectReader()" : "null")}"
            : "";

        _code.AppendLine("/// <summary>Registers the generated methods with ToonSerializer.</summary>");
        _code.AppendLine("#pragma warning disable CA2255 // Registration has to run before ToonSerializer sees the type");
        _code.AppendLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        _code.AppendLine(HiddenAttribute);
        _code.AppendLine($"internal static void __ToonRegister() => {Helpers}.Register<{_model.FullyQualifiedName}>(__ToonSerializeValue, {deserialize}{writer});");
        _code.AppendLine("#pragma warning restore CA2255");
        _code.AppendLine();

        if (_model.TypeInfoProperty == TypeInfoProperty.None)
        {
            return;
        }

        if (_model.Documentation)
        {
            _code.AppendLine("/// <summary>");
            _code.AppendLine("/// The serialization code of this type for the <see cref=\"global::ToonNet.Core.Serialization.ToonSerializer\"/> overloads that take a");
            _code.AppendLine("/// type info, which need no reflection (trimming and NativeAOT).");
            _code.AppendLine("/// </summary>");
        }

        var modifier = _model.TypeInfoProperty == TypeInfoProperty.EmitNew ? "new " : "";
        _code.AppendLine($"{Accessibility()} {modifier}static global::ToonNet.Core.Serialization.ToonTypeInfo<{_model.FullyQualifiedName}> ToonTypeInfo => " +
                         $"global::ToonNet.Core.Serialization.ToonTypeInfo.GetGenerated<{_model.FullyQualifiedName}>();");
        _code.AppendLine();
    }

    #region Serialize

    /// <summary>The public static <c>Serialize</c> method, which returns a document.</summary>
    private void EmitSerializeMethod()
    {
        var code = _code;
        var model = _model;

        if (model.Documentation)
        {
            code.AppendLine("/// <summary>");
            code.AppendLine("/// Converts an instance to a TOON document, with the same output as <see cref=\"global::ToonNet.Core.Serialization.ToonSerializer\"/>.");
            code.AppendLine("/// </summary>");
            code.AppendLine("/// <param name=\"value\">The instance to serialize.</param>");
            code.AppendLine("/// <param name=\"options\">Serialization options (defaults when null).</param>");
            code.AppendLine("/// <returns>A TOON document.</returns>");
        }

        code.BeginBlock($"{Accessibility()} static {Models}ToonDocument Serialize({model.FullyQualifiedName} value, {Options}? options = null)");

        if (model.NullChecks && !model.IsValueType)
        {
            code.AppendLine("global::System.ArgumentNullException.ThrowIfNull(value);");
        }

        code.AppendLine($"options ??= {Options}.Default;");
        code.AppendLine($"return new {Models}ToonDocument(__ToonSerializeValue(value, options, 0));");
        code.EndBlock();
        code.AppendLine();
    }

    private void EmitSerialize()
    {
        var code = _code;
        var model = _model;

        if (model.EmitSerializeMethod)
        {
            EmitSerializeMethod();
        }

        code.AppendLine("/// <summary>Used by generated code; call <c>Serialize</c> instead.</summary>");
        code.AppendLine(HiddenAttribute);
        code.BeginBlock($"public static {Models}ToonValue __ToonSerializeValue({model.FullyQualifiedName} value, {Options} options, int depth)");

        if (!model.IsValueType)
        {
            code.AppendLine($"if (value is null) return {Models}ToonNull.Instance;");
        }

        code.AppendLine($"{Helpers}.CheckSerializationDepth(options, depth);");

        var reflection = $"{Helpers}.SerializeWithReflection<{model.FullyQualifiedName}>(value, options, depth)";

        if (model.HasTypeConverter)
        {
            code.AppendLine($"return {reflection};");
            code.EndBlock();
            return;
        }

        var fallback = model.CheckRuntimeType
            ? $"options.Converters.Count != 0 || value.GetType() != typeof({model.TypeOfName})"
            : "options.Converters.Count != 0";

        code.AppendLine("// Converters and derived types are handled by ToonSerializer, which knows the runtime type.");
        code.AppendLine($"if ({fallback}) return {reflection};");
        EmitPolicyLocal();
        code.AppendLine($"var __obj = new {Models}ToonObject({model.Properties.Length});");

        for (var i = 0; i < model.Properties.Length; i++)
        {
            var property = model.Properties[i];
            var name = NameExpression(property);
            var local = $"__v{i}";

            code.AppendLine();
            code.AppendLine($"// {property.Name}");
            code.BeginBlock(property.IsReadOnly ? "if (options.IncludeReadOnlyProperties)" : "");
            code.AppendLine($"var {local} = value.{Identifier(property)};");

            if (property.ConverterTypeName != null)
            {
                EmitNullCheck(property.Plan, local, $"__obj.Properties[{name}]", () =>
                {
                    code.AppendLine($"var __t{i} = {ConverterField(property)}.Write({local}, options);");
                    code.AppendLine($"if (__t{i} is not null) __obj.Properties[{name}] = __t{i};");
                });
            }
            else
            {
                EmitStore($"__obj.Properties[{name}]", property.Plan, local, "depth + 1");
            }

            code.EndBlock();
        }

        code.AppendLine();
        code.AppendLine("return __obj;");
        code.EndBlock();
    }

    /// <summary>Stores a value in an object slot; nulls follow <c>IgnoreNullValues</c>, like ToonSerializer.</summary>
    private void EmitStore(string target, ValuePlan plan, string local, string depth)
    {
        EmitNullCheck(plan, local, target, () => _code.AppendLine($"{target} = {WriteExpression(plan, NonNull(plan, local), depth)};"));
    }

    private void EmitNullCheck(ValuePlan plan, string local, string target, Action write)
    {
        if (!plan.CanBeNull)
        {
            write();
            return;
        }

        _code.BeginBlock($"if ({local} is null)");
        _code.AppendLine($"if (!options.IgnoreNullValues) {target} = {Models}ToonNull.Instance;");
        _code.EndBlock();
        _code.BeginBlock("else");
        write();
        _code.EndBlock();
    }

    /// <summary>An expression converting a non-null value to a <c>ToonValue</c>.</summary>
    private string WriteExpression(ValuePlan plan, string value, string depth)
    {
        return plan.Kind switch
        {
            ValueKind.Inline => plan.Inline switch
            {
                PrimitiveKind.String => $"new {Models}ToonString({value})",
                PrimitiveKind.Boolean => $"new {Models}ToonBoolean({value})",
                PrimitiveKind.Integer => $"new {Models}ToonNumber((long){value})",
                _ => $"new {Models}ToonNumber({value})"
            },
            ValueKind.Primitive => $"{Helpers}.WritePrimitive<{plan.ValueTypeName}>({value})",
            ValueKind.Raw => value,
            ValueKind.Generated => $"{plan.ValueTypeName}.__ToonSerializeValue({value}, options, {depth})",
            ValueKind.Reflection => $"{Helpers}.SerializeWithReflection<{plan.ValueTypeName}>({value}, options, {depth})",
            _ => $"{WriterName(plan)}({value}, options, {depth})"
        };
    }

    private static string NonNull(ValuePlan plan, string local) => plan.IsNullableValueType ? $"{local}.GetValueOrDefault()" : local;

    #endregion

    #region Direct writing

    /// <summary>
    /// Types with a type-level converter are always written through it, so they get no field writer.
    /// </summary>
    private bool EmitsFieldWriter => !_model.HasTypeConverter;

    /// <summary>
    /// Emits the methods that write the type straight to TOON text (<c>__ToonWriteFields</c>, the tabular row methods)
    /// and the <c>ToonObjectWriter</c> that registers them. They mirror <c>__ToonSerializeValue</c> followed by the
    /// encoder; values they do not write themselves go to <c>ToonWriter.WriteField</c>, which applies ToonSerializer's
    /// rules.
    /// </summary>
    private void EmitFieldWriter()
    {
        var code = _code;
        var model = _model;
        var type = model.FullyQualifiedName;
        var duplicates = DuplicateNameCondition();

        code.AppendLine();
        code.AppendLine("/// <summary>Used by generated code and ToonSerializer; call <c>Serialize</c> instead.</summary>");
        code.AppendLine(HiddenAttribute);
        code.BeginBlock($"public static int __ToonWriteFields({type} value, {Writer} writer, int lineDepth, int childDepth, bool firstOnCurrentLine, int depth)");
        code.AppendLine("var options = writer.SerializerOptions;");
        EmitPolicyLocal();

        // Properties sharing a name: the tree keeps the last value, so write what it builds
        var treeFields = $"return writer.WriteTreeFields(({Models}ToonObject)__ToonSerializeValue(value, options, depth), lineDepth, childDepth, firstOnCurrentLine);";

        if (duplicates == "true")
        {
            code.AppendLine(treeFields);
            code.EndBlock();
            EmitRowShape(duplicates);
            EmitWriteRow();
            EmitMayBeKeyed(duplicates);
            EmitGetName();
            EmitObjectWriterClass();
            return;
        }

        if (duplicates != null)
        {
            code.BeginBlock($"if ({duplicates})");
            code.AppendLine(treeFields);
            code.EndBlock();
        }

        code.AppendLine("var __count = 0;");

        for (var i = 0; i < model.Properties.Length; i++)
        {
            var property = model.Properties[i];
            code.AppendLine();
            code.AppendLine($"// {property.Name}");
            code.BeginBlock(property.IsReadOnly ? "if (options.IncludeReadOnlyProperties)" : "");
            code.AppendLine($"var __v{i} = value.{Identifier(property)};");
            EmitWriteField(property, $"__v{i}");
            code.EndBlock();
        }

        code.AppendLine();
        code.AppendLine("return __count;");
        code.EndBlock();

        EmitRowShape(duplicates);
        EmitWriteRow();
        EmitMayBeKeyed(duplicates);
        EmitGetName();
        EmitObjectWriterClass();
    }

    /// <summary>A condition that is true for the naming policies under which two properties share a name, or null.</summary>
    private string? DuplicateNameCondition()
    {
        var policyType = Serialization + "PropertyNamingPolicy";
        var duplicate = new bool[4];

        for (var policy = 0; policy < 4; policy++)
        {
            var seen = new HashSet<string>(StringComparer.Ordinal);
            duplicate[policy] = _model.Properties.Items.Any(p => !seen.Add(p.Names[policy]));
        }

        if (_model.FixedNamingPolicy is { } fixedPolicy)
        {
            return duplicate[fixedPolicy is >= 0 and <= 3 ? fixedPolicy : 0] ? "true" : null;
        }

        if (!duplicate.Any(d => d))
        {
            return null;
        }

        // Undefined policy values use the property names as they are, like the default policy
        return $"__policy switch {{ {policyType}.CamelCase => {Bool(duplicate[1])}, {policyType}.SnakeCase => {Bool(duplicate[2])}, " +
               $"{policyType}.LowerCase => {Bool(duplicate[3])}, _ => {Bool(duplicate[0])} }}";

        static string Bool(bool value) => value ? "true" : "false";
    }

    /// <summary>Writes one property in <c>__ToonWriteFields</c>, counting it in <c>__count</c> when it is written.</summary>
    private void EmitWriteField(PropertyModel property, string local)
    {
        var code = _code;
        var plan = property.Plan;
        var delegated = $"writer.WriteField({NameExpression(property)}, {local}, typeof({property.TypeOfName}), " +
                        $"{(property.ConverterTypeName != null ? ConverterField(property) : "null")}, lineDepth, childDepth, " +
                        "__count != 0 || !firstOnCurrentLine, depth + 1)";

        if (property.ConverterTypeName != null || !WritesDirectly(plan))
        {
            code.AppendLine($"if ({delegated}) __count++;");
            return;
        }

        if (plan.CanBeNull)
        {
            code.BeginBlock($"if ({local} is null)");
            code.BeginBlock("if (!options.IgnoreNullValues)");
            code.AppendLine(StartLine);
            code.AppendLine($"writer.Write({EncodedNameExpression(property, ": null")});");
            code.AppendLine("__count++;");
            code.EndBlock();
            code.EndBlock();
            code.BeginBlock("else");
        }

        var value = NonNull(plan, local);

        switch (plan.Kind)
        {
            case ValueKind.Generated:
            {
                // Objects of exactly the declared type are written by its field writer; derived types need their own,
                // and an object that may be a keyed tabular object (§9.5) needs the serializer to decide
                var keyedCheck = $"!{plan.ValueTypeName}.__ToonMayBeKeyed({value}, writer)";
                code.BeginBlock(plan.CheckRuntimeType ? $"if ({value}.GetType() == typeof({plan.ValueTypeName}) && {keyedCheck})" : $"if ({keyedCheck})");
                code.AppendLine(StartLine);
                code.AppendLine("writer.EnterValue(depth + 1);");
                code.AppendLine($"writer.Write({EncodedNameExpression(property, ":")});");
                code.AppendLine("writer.EnterNesting();");
                code.AppendLine($"{plan.ValueTypeName}.__ToonWriteFields({value}, writer, childDepth, childDepth + 1, false, depth + 1);");
                code.AppendLine("writer.ExitNesting();");
                code.AppendLine("__count++;");
                code.EndBlock();
                code.AppendLine($"else if ({delegated}) __count++;");
                break;
            }
            case ValueKind.Array or ValueKind.List or ValueKind.Set:
                EmitInlineCollection(property, value, delegated);
                break;
            default:
                code.AppendLine(StartLine);
                code.AppendLine($"writer.Write({EncodedNameExpression(property, ": ")});");
                code.AppendLine(WritePrimitiveStatement(plan, value));
                code.AppendLine("__count++;");
                break;
        }

        if (plan.CanBeNull)
        {
            code.EndBlock();
        }
    }

    private const string StartLine = "if (__count != 0 || !firstOnCurrentLine) writer.StartLine(lineDepth);";

    /// <summary>
    /// Writes a collection of primitives as an inline array (<c>key[N]: a,b</c>, or <c>key: []</c>), like the encoder
    /// writes the array the tree holds; a collection whose count is not known without enumerating goes to
    /// <c>ToonWriter.WriteField</c>.
    /// </summary>
    private void EmitInlineCollection(PropertyModel property, string value, string delegated)
    {
        var code = _code;
        var element = property.Plan.Element!;
        var count = $"__n{_variable++}";
        var first = $"__first{_variable++}";
        var item = $"__item{_variable++}";

        // Only the collection types generated code knows: another runtime type (a derived type, one with a converter,
        // a string declared as IEnumerable<char>) goes to the serializer, which knows its rules
        code.BeginBlock($"if (({KnownCollectionCondition(property.Plan, value)}) && global::System.Linq.Enumerable.TryGetNonEnumeratedCount({value}, out var {count}))");
        code.AppendLine(StartLine);
        code.AppendLine("writer.EnterValue(depth + 1);");
        code.BeginBlock($"if ({count} == 0)");
        code.AppendLine("writer.CheckEmptyNesting();");
        code.AppendLine($"writer.Write({EncodedNameExpression(property, ": []")});");
        code.EndBlock();
        code.BeginBlock("else");
        code.AppendLine("writer.EnterNesting();");
        code.AppendLine($"writer.WriteEncodedArrayHeader({EncodedNameExpression(property, "")}, {count});");
        code.AppendLine("writer.Write(\": \");");
        code.AppendLine($"var {first} = true;");
        code.BeginBlock($"foreach (var {item} in {value})");
        code.AppendLine($"if (!{first}) writer.WriteDelimiter();");
        code.AppendLine($"{first} = false;");
        code.AppendLine(element.CanBeNull
                            ? $"if ({item} is null) writer.WriteNull(); else {WritePrimitiveStatement(element, NonNull(element, item))}"
                            : WritePrimitiveStatement(element, item));
        code.EndBlock();
        code.AppendLine("writer.ExitNesting();");
        code.EndBlock();
        code.AppendLine("__count++;");
        code.EndBlock();
        code.AppendLine($"else if ({delegated}) __count++;");
    }

    /// <summary>
    /// Whether <c>__ToonWriteFields</c> writes the value itself: primitives, collections of primitives, and objects with
    /// generated field writers. Others need ToonSerializer's rules (runtime types, dictionaries, nested collections).
    /// </summary>
    private static bool WritesDirectly(ValuePlan plan) =>
        plan.Kind is ValueKind.Inline or ValueKind.Primitive ||
        plan is { Kind: ValueKind.Generated, HasFieldWriter: true, HasKeyedCheck: true } ||
        plan is { Kind: ValueKind.Array or ValueKind.List or ValueKind.Set, Element.Kind: ValueKind.Inline or ValueKind.Primitive };

    private static string WritePrimitiveStatement(ValuePlan plan, string value)
    {
        if (plan.Kind == ValueKind.Primitive && plan.EnumCases.Length > 0)
        {
            // Enum names known at compile time, without boxing the value; other values (flag combinations) use ToString
            var cases = string.Join(", ", plan.EnumCases.Items.Select(entry =>
            {
                var separator = entry.IndexOf('\0');
                return $"({plan.ValueTypeName})({entry.Substring(0, separator)}) => {Literal(entry.Substring(separator + 1))}";
            }));

            return $"writer.WriteString({value} switch {{ {cases}, var __e => __e.ToString() }});";
        }

        return plan.Kind == ValueKind.Primitive
            ? $"writer.WritePrimitiveValue<{plan.ValueTypeName}>({value});"
            : plan.Inline switch
            {
                PrimitiveKind.String => $"writer.WriteString({value});",
                PrimitiveKind.Boolean => $"writer.WriteBoolean({value});",
                PrimitiveKind.Integer => $"writer.WriteInteger((long){value});",
                PrimitiveKind.UInt64 => $"writer.WriteDecimal({value});",
                PrimitiveKind.Single => $"writer.WriteSingle({value});",
                PrimitiveKind.Decimal => $"writer.WriteDecimal({value});",
                _ => $"writer.WriteDouble({value});"
            };
    }

    /// <summary>
    /// Emits <c>__ToonGetRowShape</c>: whether an object can be a tabular row and which properties are columns.
    /// </summary>
    private void EmitRowShape(string? duplicates)
    {
        var code = _code;
        var model = _model;

        code.AppendLine();
        code.AppendLine(HiddenAttribute);
        code.BeginBlock($"public static {RowShape} __ToonGetRowShape({model.FullyQualifiedName} value, {Writer} writer, global::System.Span<bool> columns)");
        code.AppendLine("var options = writer.SerializerOptions;");

        if (duplicates == "true")
        {
            code.AppendLine($"return {RowShape}.Unknown;");
            code.EndBlock();
            return;
        }

        if (duplicates != null)
        {
            EmitPolicyLocal();
            code.AppendLine($"if ({duplicates}) return {RowShape}.Unknown;");
        }

        code.AppendLine("var __unknown = false;");

        for (var i = 0; i < model.Properties.Length; i++)
        {
            var property = model.Properties[i];
            var plan = property.Plan;
            var access = $"value.{Identifier(property)}";

            code.AppendLine();
            code.AppendLine($"// {property.Name}");

            if (property.IsReadOnly)
            {
                code.AppendLine("if (!options.IncludeReadOnlyProperties) columns[" + i + "] = false;");
                code.BeginBlock("else");
            }
            else
            {
                code.BeginBlock("");
            }

            if (property.ConverterTypeName != null)
            {
                code.AppendLine("__unknown = true; // the converter decides the form");
            }
            else if (plan.Kind is ValueKind.Inline or ValueKind.Primitive)
            {
                code.AppendLine(plan.CanBeNull
                                    ? $"columns[{i}] = !({access} is null && options.IgnoreNullValues);"
                                    : $"columns[{i}] = true;");
            }
            else
            {
                // A null value is a primitive; an array rules the row out; an object may form a nested field group (§9.3)
                // and a runtime-typed value may be anything, which the serializer decides from the tree
                var nonNull = plan.Kind is ValueKind.Array or ValueKind.List or ValueKind.Set ? $"return {RowShape}.NotRow;" : "__unknown = true;";

                if (plan.CanBeNull)
                {
                    code.AppendLine($"if ({access} is null) columns[{i}] = !options.IgnoreNullValues;");
                    code.AppendLine($"else {nonNull}");
                }
                else
                {
                    code.AppendLine(nonNull);
                }
            }

            code.EndBlock();
        }

        code.AppendLine();
        code.AppendLine($"return __unknown ? {RowShape}.Unknown : {RowShape}.Row;");
        code.EndBlock();
    }

    /// <summary>Emits <c>__ToonWriteRow</c>: the column values of a row, separated by the delimiter.</summary>
    private void EmitWriteRow()
    {
        var code = _code;
        var model = _model;

        code.AppendLine();
        code.AppendLine(HiddenAttribute);
        code.BeginBlock($"public static void __ToonWriteRow({model.FullyQualifiedName} value, {Writer} writer, global::System.ReadOnlySpan<bool> columns)");
        code.AppendLine("var __first = true;");

        for (var i = 0; i < model.Properties.Length; i++)
        {
            var property = model.Properties[i];
            var plan = property.Plan;

            code.BeginBlock($"if (columns[{i}])");
            code.AppendLine("if (!__first) writer.WriteDelimiter();");
            code.AppendLine("__first = false;");

            if (property.ConverterTypeName == null && plan.Kind is ValueKind.Inline or ValueKind.Primitive)
            {
                if (plan.CanBeNull)
                {
                    code.AppendLine($"var __v{i} = value.{Identifier(property)};");
                    code.AppendLine($"if (__v{i} is null) writer.WriteNull(); else {WritePrimitiveStatement(plan, NonNull(plan, $"__v{i}"))}");
                }
                else
                {
                    code.AppendLine(WritePrimitiveStatement(plan, $"value.{Identifier(property)}"));
                }
            }
            else
            {
                code.AppendLine("writer.WriteNull(); // only null values of other properties are rows");
            }

            code.EndBlock();
        }

        code.EndBlock();
    }

    /// <summary>
    /// Emits <c>__ToonMayBeKeyed</c>: whether the object may qualify for the keyed tabular form (spec §9.5) in a field or
    /// root position, i.e. it writes at least two fields and each is an object. False as soon as a written value is a
    /// primitive or array; a type with a property that is always written as a primitive never qualifies.
    /// </summary>
    private void EmitMayBeKeyed(string? duplicates)
    {
        var code = _code;
        var model = _model;

        code.AppendLine();
        code.AppendLine(HiddenAttribute);
        code.BeginBlock($"public static bool __ToonMayBeKeyed({model.FullyQualifiedName} value, {Writer} writer)");

        if (duplicates == "true")
        {
            code.AppendLine("return true; // the tree decides");
            code.EndBlock();
            return;
        }

        var alwaysPrimitive = model.Properties.Items.Any(p => !p.IsReadOnly && p.ConverterTypeName == null && IsWrittenAsPrimitive(p.Plan) &&
                                                               !p.Plan.CanBeNull);

        if (alwaysPrimitive && duplicates == null)
        {
            code.AppendLine("return false;");
            code.EndBlock();
            return;
        }

        code.AppendLine("var options = writer.SerializerOptions;");

        if (duplicates != null)
        {
            // Properties sharing a name replace each other in the tree, so only the tree knows then
            EmitPolicyLocal();
            code.AppendLine($"if ({duplicates}) return true;");

            if (alwaysPrimitive)
            {
                code.AppendLine("return false;");
                code.EndBlock();
                return;
            }
        }

        code.AppendLine("var __objects = 0;");
        code.AppendLine("var __maybe = false;");

        foreach (var property in model.Properties)
        {
            var plan = property.Plan;
            var access = $"value.{Identifier(property)}";

            code.BeginBlock(property.IsReadOnly ? "if (options.IncludeReadOnlyProperties)" : "");

            if (property.ConverterTypeName != null)
            {
                code.AppendLine("__maybe = true; // the converter decides the form");
            }
            else if (IsWrittenAsPrimitive(plan))
            {
                // A primitive or array, or a null that is written
                code.AppendLine(plan.CanBeNull ? $"if ({access} is not null || !options.IgnoreNullValues) return false;" : "return false;");
            }
            else
            {
                // An object, or a runtime-typed value only the tree knows
                var nonNull = plan.Kind is ValueKind.Raw or ValueKind.Reflection ? "__maybe = true;" : "__objects++;";

                if (plan.CanBeNull)
                {
                    code.AppendLine($"if ({access} is null) {{ if (!options.IgnoreNullValues) return false; }}");
                    code.AppendLine($"else {nonNull}");
                }
                else
                {
                    code.AppendLine(nonNull);
                }
            }

            code.EndBlock();
        }

        code.AppendLine("return __maybe || __objects >= 2;");
        code.EndBlock();

        static bool IsWrittenAsPrimitive(ValuePlan plan) =>
            plan.Kind is ValueKind.Inline or ValueKind.Primitive or ValueKind.Array or ValueKind.List or ValueKind.Set;
    }

    /// <summary>
    /// Emits <c>GetPropertyKind</c>, <c>GetValue</c> and <c>WriteValue</c> of the object writer: per property index, how
    /// it is written, its value, and (for primitives) the value written as a row cell.
    /// </summary>
    private void EmitPropertyAccess(string type)
    {
        var code = _code;
        var properties = _model.Properties;
        var kind = Serialization + "ToonPropertyKind";

        EmitInlineTypes();

        code.BeginBlock($"public override {kind} GetPropertyKind(int index) => index switch");

        for (var i = 0; i < properties.Length; i++)
        {
            var property = properties[i];
            var name = property.ConverterTypeName != null ? "Dynamic" : property.Plan.Kind switch
            {
                ValueKind.Inline or ValueKind.Primitive => "Primitive",
                ValueKind.Array or ValueKind.List or ValueKind.Set => "Array",
                ValueKind.Generated or ValueKind.Dictionary => "Object",
                _ => "Dynamic"
            };

            code.AppendLine($"{i} => {kind}.{name},");
        }

        code.AppendLine("_ => throw new global::System.ArgumentOutOfRangeException(nameof(index))");
        code.EndBlock(";");

        var readOnly = properties.Items.Select((p, i) => (p, i)).Where(t => t.p.IsReadOnly).Select(t => t.i.ToString()).ToList();
        code.AppendLine(readOnly.Count == 0
                            ? "public override bool IsReadOnlyProperty(int index) => false;"
                            : $"public override bool IsReadOnlyProperty(int index) => index is {string.Join(" or ", readOnly)};");

        code.BeginBlock($"public override object? GetValue({type} value, int index) => index switch");

        for (var i = 0; i < properties.Length; i++)
        {
            code.AppendLine($"{i} => value.{Identifier(properties[i])},");
        }

        code.AppendLine("_ => throw new global::System.ArgumentOutOfRangeException(nameof(index))");
        code.EndBlock(";");

        code.BeginBlock($"public override void WriteValue({type} value, int index, {Writer} writer)");

        // Only primitive properties are written as cells (an empty switch would be a warning)
        var cells = Enumerable.Range(0, properties.Length)
                              .Where(i => properties[i].ConverterTypeName == null && properties[i].Plan.Kind is ValueKind.Inline or ValueKind.Primitive)
                              .ToList();

        if (cells.Count > 0)
        {
            code.BeginBlock("switch (index)");
        }

        foreach (var i in cells)
        {
            var property = properties[i];
            var plan = property.Plan;

            code.BeginBlock($"case {i}:");

            if (plan.CanBeNull)
            {
                code.AppendLine($"var __v{i} = value.{Identifier(property)};");
                code.AppendLine($"if (__v{i} is null) writer.WriteNull(); else {WritePrimitiveStatement(plan, NonNull(plan, $"__v{i}"))}");
            }
            else
            {
                code.AppendLine(WritePrimitiveStatement(plan, $"value.{Identifier(property)}"));
            }

            code.AppendLine("return;");
            code.EndBlock();
        }

        if (cells.Count > 0)
        {
            code.EndBlock();
        }

        code.AppendLine("throw new global::System.ArgumentOutOfRangeException(nameof(index));");
        code.EndBlock();
    }

