using System.Buffers;
using System.ComponentModel;
using System.Globalization;
using System.Runtime.CompilerServices;
using ToonNet.Core.Models;
using ToonNet.Core.Serialization;

namespace ToonNet.Core.Encoding;

/// <summary>
///     Where an array is written, which decides how an empty array is represented and whether the tabular form may be
///     used (spec §9.1-§9.3).
/// </summary>
internal enum ToonArrayPosition
{
    Root,
    Field,
    ListItem
}

/// <summary>
///     Writes the pieces of TOON text into a <see cref="ToonTextBuffer"/>: lines and indentation, keys, primitive
///     values and array headers, with the quoting, escaping and number rules of the spec (§2, §6, §7, §12).
/// </summary>
/// <remarks>
///     <para>
///     It holds no document structure: the encoder drives it from a <see cref="ToonValue"/> tree, and the serializer
///     and source-generated code drive it directly from .NET objects, so all produce the same text. It also tracks the
///     nesting depth for <see cref="ToonOptions.MaxDepth"/>. An instance writes one document and is not thread-safe.
///     </para>
///     <para>
///     This type supports code generated by <c>ToonNet.SourceGenerators</c> and is not intended to be used directly;
///     generated code needs <c>ToonNet.Core</c> of the same release.
///     </para>
/// </remarks>
[EditorBrowsable(EditorBrowsableState.Never)]
public sealed class ToonWriter
{
    private const string HexDigits = "0123456789abcdef";

    private readonly ToonTextBuffer _buffer;
    private bool _hasLine;

    /// <summary>Whether the value being written is the document's root primitive.</summary>
    private bool _rootPrimitive;

    internal ToonWriter(ToonTextBuffer buffer, ToonOptions options)
    {
        _buffer = buffer;
        Options = options;
    }

    /// <summary>The encoding options.</summary>
    public ToonOptions Options { get; }

    /// <summary>
    ///     The serializer writing the document; set when objects are written directly (not by the encoder).
    /// </summary>
    internal IToonSerializationHost? Host { get; set; }

    /// <summary>The serialization options of the serializer writing the document.</summary>
    /// <exception cref="InvalidOperationException">Thrown when the writer is not used by the serializer.</exception>
    public ToonSerializerOptions SerializerOptions => RequireHost().Options;

    /// <summary>The delimiter of inline arrays and tabular rows.</summary>
    public char Delimiter => Options.Delimiter;

    /// <summary>
    ///     The nesting depth of the current object or array; the root value is at depth 0 (a root array starts at -1
    ///     before it is entered).
    /// </summary>
    internal int Nesting { get; set; }

    #region Structure

    /// <summary>
    ///     Starts a new line at the given depth. Lines are separated by LF and the document has no trailing newline
    ///     (spec §12).
    /// </summary>
    public void StartLine(int depth)
    {
        if (_hasLine)
        {
            _buffer.Append('\n');
        }

        _hasLine = true;
        _buffer.Append(' ', depth * Options.IndentSize);
    }

    /// <summary>
    ///     Enters the level of a nested object or array, enforcing <see cref="ToonOptions.MaxDepth"/> (the root value
    ///     is at depth 0, each object or array inside another one level deeper) and the available stack space.
    /// </summary>
    /// <exception cref="ToonEncodingException">Thrown when the document is nested too deeply.</exception>
    public void EnterNesting()
    {
        if (++Nesting > Options.ValidatedMaxDepth)
        {
            throw new ToonEncodingException($"Maximum depth of {Options.MaxDepth} exceeded");
        }

        if (!RuntimeHelpers.TryEnsureSufficientExecutionStack())
        {
            throw new ToonEncodingException("Document is nested too deeply to encode with the available stack space");
        }
    }

    /// <summary>Leaves the level entered with <see cref="EnterNesting"/>.</summary>
    public void ExitNesting() => Nesting--;

    /// <summary>
    ///     Checks the depth of an empty object or array, which has no content that would enter its level.
    /// </summary>
    public void CheckEmptyNesting()
    {
        EnterNesting();
        Nesting--;
    }

    /// <summary>The number of characters written to the buffer so far.</summary>
    internal int Position => _buffer.Length;

    /// <summary>
    ///     Discards what was written after <paramref name="position"/>, which must be on the current line (no line was
    ///     started since).
    /// </summary>
    internal void Truncate(int position) => _buffer.Truncate(position);

    /// <summary>Writes text as it is (an encoded key, a separator).</summary>
    public void Write(char value) => _buffer.Append(value);

    /// <summary>Writes text as it is (an encoded key, a separator).</summary>
    public void Write(string value) => _buffer.Append(value);

    /// <summary>Writes the delimiter of inline arrays and tabular rows.</summary>
    public void WriteDelimiter() => _buffer.Append(Options.Delimiter);

    /// <summary>
    ///     Writes <c>key[N]</c> (the key is optional) including the delimiter symbol for tab and pipe (spec §6).
    /// </summary>
    public void WriteArrayHeader(string? key, int count)
    {
        if (key != null)
        {
            WriteKey(key);
        }

        _buffer.Append('[');
        count.TryFormat(_buffer.GetSpan(11), out var length, default, CultureInfo.InvariantCulture);
        _buffer.Advance(length);

        if (Options.Delimiter != ',')
        {
            _buffer.Append(Options.Delimiter);
        }

        _buffer.Append(']');
    }

    /// <summary>
    ///     Writes <c>key[N]</c> for a key already encoded (quoted when needed), as generated code encodes keys at
    ///     compile time.
    /// </summary>
    public void WriteEncodedArrayHeader(string encodedKey, int count)
    {
        _buffer.Append(encodedKey);
        WriteArrayHeader(null, count);
    }

    /// <summary>
    ///     Writes <c>key[N:]</c>, the start of a keyed tabular object's header (spec §9.5); the key is null at the root.
    /// </summary>
    internal void WriteKeyedHeader(string? key, int count)
    {
        if (key != null)
        {
            WriteKey(key);
        }

        _buffer.Append('[');
        count.TryFormat(_buffer.GetSpan(11), out var length, default, CultureInfo.InvariantCulture);
        _buffer.Advance(length);
        _buffer.Append(':');

        if (Options.Delimiter != ',')
        {
            _buffer.Append(Options.Delimiter);
        }

        _buffer.Append(']');
    }

    /// <summary>
    ///     Writes the field list of a tabular or keyed header with its nested field groups, <c>{a,b{c,d}}:</c>
    ///     (spec §9.3).
    /// </summary>
    internal void WriteFieldList(ReadOnlySpan<ToonColumn> columns)
    {
        WriteFieldGroup(columns, 0, columns.Length);
        _buffer.Append(':');
    }

    private void WriteFieldGroup(ReadOnlySpan<ToonColumn> columns, int start, int end)
    {
        _buffer.Append('{');

        for (var i = start; i < end; i = columns[i].End)
        {
            if (i > start)
            {
                _buffer.Append(Options.Delimiter);
            }

            WriteKey(columns[i].Name);

            if (columns[i].IsGroupAt(i))
            {
                WriteFieldGroup(columns, i + 1, columns[i].End);
            }
        }

        _buffer.Append('}');
    }

    /// <summary>
    ///     Writes the field list of a tabular array header, <c>{a,b}:</c> (spec §9.3).
    /// </summary>
    internal void WriteFieldList(ReadOnlySpan<string> fields)
    {
        _buffer.Append('{');

        for (var i = 0; i < fields.Length; i++)
        {
            if (i > 0)
            {
                _buffer.Append(Options.Delimiter);
            }

            WriteKey(fields[i]);
        }

        _buffer.Append("}:");
    }

    #endregion

    #region Keys and primitives

    /// <summary>
    ///     Writes a key or tabular field name, quoting it unless it matches <c>^[A-Za-z_][A-Za-z0-9_.]*$</c> (spec §7.3).
    /// </summary>
    public void WriteKey(string key)
    {
        if (Shared.ToonKeys.IsSafeUnquoted(key))
        {
            _buffer.Append(key);
        }
        else
        {
            WriteQuoted(key);
        }
    }

    /// <summary>Writes a key that is always quoted and has nothing to escape (a formatted integer or GUID).</summary>
    internal void WriteQuotedKey(ReadOnlySpan<char> key)
    {
        _buffer.Append('"');
        _buffer.Append(key);
        _buffer.Append('"');
    }

    /// <summary>
    ///     Writes a primitive value. NaN and infinities are written as null (spec §3).
    /// </summary>
    /// <exception cref="ToonEncodingException">Thrown for objects, arrays and unknown <see cref="ToonValue"/> subclasses.</exception>
    public void WritePrimitive(ToonValue? value)
    {
        switch (value)
        {
            case null or ToonNull:
                WriteNull();
                break;
            case ToonBoolean b:
                WriteBoolean(b.Value);
                break;
            case ToonNumber n:
                WriteNumber(n);
                break;
            case ToonString s:
                WriteString(s.Value);
                break;
            default:
                throw new ToonEncodingException($"Unsupported TOON value type: {value.GetType().Name}");
        }
    }

    /// <summary>Writes <c>null</c>.</summary>
    public void WriteNull() => _buffer.Append("null");

    /// <summary>Writes <c>true</c> or <c>false</c>.</summary>
    public void WriteBoolean(bool value) => _buffer.Append(value ? "true" : "false");

    /// <summary>Writes a number in canonical form (NaN and infinities as null).</summary>
    public void WriteNumber(ToonNumber number)
    {
        if (ToonNumberFormatter.TryFormat(number, _buffer.GetSpan(ToonNumberFormatter.MaxLength), out var written))
        {
            _buffer.Advance(written);
        }
        else
        {
            WriteNull();
        }
    }

    /// <summary>Writes an integer like a <see cref="ToonNumber"/> created from it.</summary>
    public void WriteInteger(long value)
    {
        value.TryFormat(_buffer.GetSpan(20), out var written, default, CultureInfo.InvariantCulture);
        _buffer.Advance(written);
    }

    /// <summary>Writes a decimal like a <see cref="ToonNumber"/> created from it.</summary>
    public void WriteDecimal(decimal value)
    {
        _buffer.Advance(ToonNumberFormatter.FormatDecimal(value, _buffer.GetSpan(ToonNumberFormatter.MaxLength)));
    }

    /// <summary>Writes a float like a <see cref="ToonNumber"/> created from it (its shortest decimal form).</summary>
    public void WriteSingle(float value) => WriteDouble(ToonNumber.SingleToDouble(value));

    /// <summary>Writes a double like a <see cref="ToonNumber"/> created from it (NaN and infinities as null).</summary>
    public void WriteDouble(double value)
    {
        if (ToonNumberFormatter.TryFormatDouble(value, _buffer.GetSpan(ToonNumberFormatter.MaxLength), out var written))
        {
            _buffer.Advance(written);
        }
        else
        {
            WriteNull();
        }
    }

    /// <summary>
    ///     Marks the value written next as the document's root primitive, which is quoted when it starts with U+FEFF so
    ///     that it is not read as a byte-order mark (spec §7.2).
    /// </summary>
    internal void BeginRootPrimitive() => _rootPrimitive = true;

    /// <summary>
    ///     Writes a string value, quoted and escaped when spec §7.2 requires it.
    /// </summary>
    public void WriteString(ReadOnlySpan<char> value)
    {
        if (NeedsQuoting(value, Options.Delimiter) || (_rootPrimitive && value[0] == '\uFEFF'))
        {
            WriteQuoted(value);
        }
        else
        {
            _buffer.Append(value);
        }
    }

    /// <summary>
    ///     Writes a quoted string, escaped per spec §7.1: backslash, quote, LF, CR and tab use short escapes,
    ///     other control characters U+0000–U+001F use lowercase <c>\uXXXX</c>. Runs of characters that need no escape
    ///     are written in one piece.
    /// </summary>
    /// <exception cref="ToonEncodingException">Thrown for an unpaired surrogate, which TOON cannot represent (§3).</exception>
    private void WriteQuoted(ReadOnlySpan<char> text)
    {
        var sb = _buffer;
        sb.Append('"');
        var start = 0;

        for (var i = 0; i < text.Length; i++)
        {
            var ch = text[i];

            if (ch is not ('\\' or '"') && ch >= ' ')
            {
                if (char.IsSurrogate(ch))
                {
                    i = SkipSurrogatePair(text, i);
                }

                continue;
            }

            sb.Append(text[start..i]);
            start = i + 1;

            switch (ch)
            {
                case '\\':
                    sb.Append("\\\\");
                    break;
                case '"':
                    sb.Append("\\\"");
                    break;
                case '\n':
                    sb.Append("\\n");
                    break;
                case '\r':
                    sb.Append("\\r");
                    break;
                case '\t':
                    sb.Append("\\t");
                    break;
                default:
                    sb.Append("\\u00").Append(HexDigits[ch >> 4]).Append(HexDigits[ch & 0xF]);
                    break;
            }
        }

        sb.Append(text[start..]).Append('"');
    }

    // Characters that need quotes anywhere in a string value (§7.2): colon, quote, backslash, brackets, braces, the
    // controls U+0000-U+001F (tab included) and the delimiter
    private const string QuotedCharacters = ":\"\\[]{}\u0000\u0001\u0002\u0003\u0004\u0005\u0006\u0007\b\t\n\u000b\f\r\u000e\u000f" +
                                            "\u0010\u0011\u0012\u0013\u0014\u0015\u0016\u0017\u0018\u0019\u001a\u001b\u001c\u001d\u001e\u001f";

    // ASCII-only sets, which SearchValues scans fastest
    private static readonly SearchValues<char> QuotedWithComma = SearchValues.Create(QuotedCharacters + ",");
    private static readonly SearchValues<char> QuotedWithPipe = SearchValues.Create(QuotedCharacters + "|");
    private static readonly SearchValues<char> QuotedWithTab = SearchValues.Create(QuotedCharacters);

    /// <summary>Returns the index of the low surrogate of the pair starting at <paramref name="index"/>.</summary>
    /// <exception cref="ToonEncodingException">Thrown when the surrogate is unpaired.</exception>
    private static int SkipSurrogatePair(ReadOnlySpan<char> text, int index)
    {
        if (char.IsHighSurrogate(text[index]) && index + 1 < text.Length && char.IsLowSurrogate(text[index + 1]))
        {
            return index + 1;
        }

        throw new ToonEncodingException($"A string contains an unpaired surrogate (U+{(int)text[index]:X4}), which TOON cannot represent");
    }

    /// <summary>
    ///     Checks the quoting rules of spec §7.2 for a string value (the root-primitive rule aside).
    /// </summary>
    /// <param name="value">The string to check.</param>
    /// <param name="delimiter">The document delimiter: comma, tab or pipe.</param>
    /// <returns><c>true</c> if the string must be quoted.</returns>
    /// <exception cref="ToonEncodingException">Thrown for an unpaired surrogate in a string that needs no quotes.</exception>
    internal static bool NeedsQuoting(ReadOnlySpan<char> value, char delimiter)
    {
        if (value.IsEmpty)
        {
            return true;
        }

        // Only SP and HTAB are whitespace (§1.2); a leading '-' or '#' would read as a list item or a comment
        var first = value[0];

        if (first is ' ' or '\t' or '-' or '#' || value[^1] is ' ' or '\t')
        {
            return true;
        }

        var quoted = delimiter switch
        {
            ',' => QuotedWithComma,
            '|' => QuotedWithPipe,
            _ => QuotedWithTab
        };

        if (value.IndexOfAny(quoted) >= 0)
        {
            return true; // writing the quoted string checks its surrogates
        }

        // Written as is, so surrogates must form pairs (§3)
        for (var i = value.IndexOfAnyInRange('\uD800', '\uDFFF'); i >= 0;)
        {
            i = SkipSurrogatePair(value, i) + 1;
            var next = value[i..].IndexOfAnyInRange('\uD800', '\uDFFF');
            i = next < 0 ? -1 : i + next;
        }

        return first switch
        {
            't' => value.SequenceEqual("true"),
            'f' => value.SequenceEqual("false"),
            'n' => value.SequenceEqual("null"),
            '+' or (>= '0' and <= '9') => IsNumericLike(value),
            // A line of three or more backticks or tildes alone (a root string, the cell of a one-field table) would
            // close the Markdown code block a prompt puts the document in; quoted, it is text
            '`' or '~' => value.Length >= 3 && value.IndexOfAnyExcept(first) < 0,
            _ => false
        };
    }

    /// <summary>
    ///     Matches <c>/^[+-]?[0-9]+(?:\.[0-9]+)?(?:e[+-]?[0-9]+)?$/i</c> (spec §7.2).
    /// </summary>
    private static bool IsNumericLike(ReadOnlySpan<char> value)
    {
        var i = 0;

        if (value[i] is '+' or '-')
        {
            i++;
        }

        if (!SkipDigits(value, ref i))
        {
            return false;
        }

        if (i < value.Length && value[i] == '.')
        {
            i++;

            if (!SkipDigits(value, ref i))
            {
                return false;
            }
        }

        if (i < value.Length && value[i] is 'e' or 'E')
        {
            i++;

            if (i < value.Length && value[i] is '+' or '-')
            {
                i++;
            }

            if (!SkipDigits(value, ref i))
            {
                return false;
            }
        }

        return i == value.Length;

        static bool SkipDigits(ReadOnlySpan<char> text, ref int index)
        {
            var start = index;

            while (index < text.Length && char.IsAsciiDigit(text[index]))
            {
                index++;
            }

            return index > start;
        }
    }

    /// <summary>
    ///     Writes a primitive (a date, <see cref="Guid"/>, enum, ...) like the serializer, without boxing the common
    ///     types.
    /// </summary>
    public void WritePrimitiveValue<T>(T value) => ToonSerializer.WriteTypedText(this, value);

    #endregion

    #region Serializer

    /// <summary>
    ///     Writes <c>key: value</c>, a nested object or an array for any value, like the serializer; generated code
    ///     calls this for values it does not write itself.
    /// </summary>
    /// <param name="key">The key (not encoded).</param>
    /// <param name="value">The value.</param>
    /// <param name="declaredType">The declared type of the value.</param>
    /// <param name="converter">A converter from <c>[ToonConverter]</c> on the property, if any.</param>
    /// <param name="lineDepth">The depth of the field's line.</param>
    /// <param name="childDepth">The depth of nested content.</param>
    /// <param name="startLine">Whether to start a new line (false for the first field of a list item).</param>
    /// <param name="depth">The serializer depth of the value.</param>
    /// <returns><c>false</c> when the field is skipped (an ignored null, or a converter that returned null).</returns>
    public bool WriteField(string key, object? value, Type declaredType, IToonConverter? converter, int lineDepth, int childDepth,
                           bool startLine, int depth)
    {
        return RequireHost().WriteField(key, value, declaredType, converter, lineDepth, childDepth, startLine, depth);
    }

    /// <summary>
    ///     The checks the serializer makes before writing an object, collection or dictionary at the given depth.
    /// </summary>
    public void EnterValue(int depth) => RequireHost().EnterValue(depth);

    /// <summary>
    ///     Writes the properties of an already converted object as fields, like <see cref="WriteField"/> writes those
    ///     of an object.
    /// </summary>
    /// <returns>The number of fields written.</returns>
    public int WriteTreeFields(ToonObject value, int lineDepth, int childDepth, bool firstOnCurrentLine)
    {
        return RequireHost().WriteTreeFields(value, lineDepth, childDepth, firstOnCurrentLine);
    }

    private IToonSerializationHost RequireHost() =>
        Host ?? throw new InvalidOperationException("This ToonWriter is not used by the serializer.");

    #endregion
}

/// <summary>
///     The serializer operations a <see cref="ToonWriter"/> forwards for generated code.
/// </summary>
internal interface IToonSerializationHost
{
    ToonSerializerOptions Options { get; }

    bool WriteField(string key, object? value, Type declaredType, IToonConverter? converter, int lineDepth, int childDepth, bool startLine,
                    int depth);

    void EnterValue(int depth);

    int WriteTreeFields(ToonObject value, int lineDepth, int childDepth, bool firstOnCurrentLine);
}
